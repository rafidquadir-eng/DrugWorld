"""D0 annotation audit (plan section 3, item 1): writes reports/D0_DATA_AUDIT.md and
results/d0/audit.json from the IDR annotation files and the idr0119 companion file map.

  PYTHONPATH=src python scripts/01_audit.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from drugworld import REPO
from drugworld import idr0119

OUT = REPO / "reports" / "D0_DATA_AUDIT.md"
RES = REPO / "results" / "d0" / "audit.json"
A64 = REPO / "data" / "annotations" / "idr0064-goglia-erkdynamics" / "screenA" / \
    "idr0064-screenA-annotation.csv"
#: read from the image records (IDR API, TIFF headers) on 2026-10-30; see the report text
IDR0064_IMAGE = {"size_xy": [512, 512], "channels": ["ErkKTR-BFP (405)", "H2B-RFP (561)"],
                 "frames": 121, "frame_interval_s": 179.99971, "fields_per_well": 1,
                 "pixel_um": 1.6, "bytes_per_well_file": 126918702}


def g(x):
    return f"{x:g}"


def main() -> int:
    fm = pd.read_parquet(REPO / "data" / "annotations" / "idr0119_files.parquet")
    ann = idr0119.annotations()
    single = ann[ann.drug2 == ""]
    combo = ann[ann.drug2 != ""]
    fields = fm.groupby(["plate", "well"]).field.nunique()
    slots = fm.groupby(["plate", "well", "field", "channel"]).slot.nunique()
    res: dict = {"idr0119": {"lines": {}}, "idr0064": {}}
    L = ["# D0 data audit (DrugWorld)", "",
         "Generated by `scripts/01_audit.py` from the IDR annotation repositories "
         "(`IDR/idr0119-gross-cellresponse` at `2db16f9`, `IDR/idr0064-goglia-erkdynamics` at "
         "`cae51ac`), the 34 idr0119 companion OME-XML files, and the image records. Numbers "
         "are counted from those files; text marked *source* is quoted or paraphrased from the "
         "study files or the papers.", "",
         "## idr0119 (Gross et al., Nat Commun 2023)", "",
         "- Licence on the record: CC BY 4.0 (`idr0119-study.txt`).",
         f"- {ann.plate.nunique()} plates, {len(ann)} wells, "
         f"{int(fields.sum())} well fields (movies); fields per well: "
         f"{fields.value_counts().sort_index().to_dict()}.",
         f"- {len(fm):,} single-plane TIFFs (uint16, 1408 x 1040), 3 channels: R = nuclear "
         "reporter (NLS-mCherry), G = cell-cycle reporter (clover-HDHB), P = phase contrast. "
         "**The reporter is HDHB, not FUCCI**: G1 vs S/G2 is read from HDHB localisation "
         "(nuclear/cytoplasmic ratio), as in the study's feature files.",
         "- Frames: every 30 min from 0 to 96 h (193 slots) on every plate, taken from the "
         "file-name time stamps. The study text says the three non-AU565 lines were imaged "
         "every 2 h; the deposited files of all 34 plates are at 30 min, so the files are used.",
         f"- Fields with all 193 slots: {int((slots == 193).sum())} of {len(slots)} "
         f"(field x channel); the rest miss 1-7 slots (listed in `results/d0/audit.json`).",
         "- **Dose units:** the library file labels compound 1 concentrations as micromolar and "
         "compound 2 as nanomolar. The paper states \"All doses in nM\" and its quoted doses "
         "(e.g. 50 nM lapatinib, 3 nM paclitaxel, 30 nM gemcitabine) match the compound 1 "
         "values, so **both columns are nM**. The plan's dose encoding (log10 of dose / the "
         "drug's maximum grid dose) does not depend on the unit.",
         "- **Timing of drug addition** (*source*: paper methods, \"After drug addition (T0), "
         "plates were imaged every 2 h [AU565: 30 min] for 96H\"): the first frame is at drug "
         "addition, so drug addition precedes the first frame by <= 1 h for every plate. Under "
         "the frozen start-state rule the well's own first clip is the start state.",
         "- *Source* (study protocol): for AU565 single-drug plates, \"at 48H the media was "
         "replaced in all wells including the control wells, and fresh media and drug were "
         "added\". This applies to AU565 single drugs only and is recorded here for the "
         "protocol (re-dosing at 48 h, between the 24 h and 72 h horizons).",
         "- *Source*: \"Four equally-spaced image locations per well and three biological "
         "replicates were collected.\"", "",
         "### Single drugs, per line", ""]
    for line, gl in single.groupby("line"):
        veh = gl[gl.drug1 == ""]
        vpp = veh.groupby("plate").size()
        L += [f"#### {line}", "",
              f"{gl.plate.nunique()} plates; vehicle wells per plate: "
              f"{sorted(vpp.reindex(gl.plate.unique(), fill_value=0).unique().tolist())} "
              f"({len(veh)} in total).", "",
              "| drug | doses (nM) | n doses | replicate wells per dose | plates |",
              "|---|---|---|---|---|"]
        lr = {"plates": int(gl.plate.nunique()), "vehicle_wells": int(len(veh)), "drugs": {}}
        for d, h in gl[gl.drug1 != ""].groupby("drug1"):
            doses = sorted(h.dose1.unique())
            reps = h.groupby("dose1").size()
            L.append(f"| {d} | {', '.join(g(x) for x in doses)} | {len(doses)} | "
                     f"{sorted(reps.unique().tolist())} | {h.plate.nunique()} |")
            lr["drugs"][d] = {"doses_nM": [float(x) for x in doses],
                              "replicates_per_dose": {g(k): int(v) for k, v in reps.items()},
                              "plates": int(h.plate.nunique())}
        res["idr0119"]["lines"][line] = lr
        L.append("")
    pairs = combo.assign(pair=[" + ".join(sorted([a, b])) for a, b in
                               zip(combo.drug1, combo.drug2)])
    pairs["cond"] = [tuple(sorted([(a, x), (b, y)])) for a, x, b, y in
                     zip(pairs.drug1, pairs.dose1, pairs.drug2, pairs.dose2)]
    L += ["### Combinations", "",
          f"AU565 only: {len(combo)} wells on {combo.plate.nunique()} plates, "
          f"{pairs.pair.nunique()} distinct (unordered) drug pairs, "
          f"{pairs.cond.nunique()} distinct dose-combination conditions.", "",
          "| pair | dose combinations (nM, nM) | conditions | wells |", "|---|---|---|---|"]
    res["idr0119"]["combinations"] = {}
    for p, h in pairs.groupby("pair"):
        conds = sorted(h.cond.unique())
        L.append(f"| {p} | " + "; ".join(f"{a[0][:4]} {g(a[1])} + {b[0][:4]} {g(b[1])}"
                                          for a, b in conds)
                 + f" | {len(conds)} | {len(h)} |")
        res["idr0119"]["combinations"][p] = {"conditions": len(conds), "wells": int(len(h))}
    L += ["", "Replicate wells per combination condition: "
          f"{pairs.groupby('cond').size().value_counts().sort_index().to_dict()}.", ""]
    # ---- idr0064
    a = pd.read_csv(A64)
    ctl = a["Control Type"].fillna("")
    drug = a[ctl == ""]
    im = IDR0064_IMAGE
    res["idr0064"] = {"plates": int(a.Plate.nunique()), "wells": int(len(a)),
                      "compounds": int(drug["Compound Name"].nunique()),
                      "doses_uM": sorted(a["Compound Concentration (microMolar)"].unique()
                                         .tolist()),
                      "wells_per_compound": drug.groupby("Compound Name").size()
                      .value_counts().to_dict(),
                      "dmso_wells_per_plate": a[ctl == "vehicle control"].groupby("Plate")
                      .size().to_dict(),
                      "untreated_wells": int((ctl == "untreated control").sum()),
                      "target_classes": drug["Compound General Target Class"].value_counts()
                      .to_dict(), **im}
    r = res["idr0064"]
    L += ["## idr0064 (Goglia et al., Cell Syst 2020)", "",
          "- Licence on the record: CC BY 4.0 (`idr0064-study.txt`).",
          f"- {r['plates']} plates (384-well), {r['wells']} imaged wells, one field per well.",
          f"- {r['compounds']} compounds, all at {r['doses_uM']} uM (one dose). Wells per "
          f"compound: {r['wells_per_compound']} (count of compounds by number of wells): "
          "**each compound is imaged in a single well, so there are no replicate wells per "
          "compound.**",
          f"- DMSO vehicle wells per plate: {r['dmso_wells_per_plate']}; untreated wells: "
          f"{r['untreated_wells']}.",
          f"- Images: {im['size_xy'][0]} x {im['size_xy'][1]} px at {im['pixel_um']} um, "
          f"2 channels ({', '.join(im['channels'])}), {im['frames']} frames at "
          f"{im['frame_interval_s'] / 60:.1f} min (ImageJ `finterval` in the TIFF header), so "
          f"{(im['frames'] - 1) * im['frame_interval_s'] / 3600:.1f} h per well; one "
          f"multi-frame TIFF per well ({im['bytes_per_well_file'] / 1e6:.0f} MB).",
          "- **Timing of drug addition** (*source*: study protocol, \"Imaging was carried out "
          "30 min after drug additions\"): 30 min before the first frame, i.e. <= 1 h, so the "
          "well's own first clip is the start state under the frozen rule. The study text says "
          "intervals of 2-3 min across the paper's experiments; the screen files record 3 min.",
          "- Target classes (vendor annotation, compounds): " +
          ", ".join(f"{k} {v}" for k, v in r["target_classes"].items()) + ".",
          "- Structures: the library file gives the CAS number and the PubChem URL (CID) per "
          "compound, no SMILES; SMILES will be taken from PubChem by CID (source recorded per "
          "compound).",
          "- Goglia's Erk-phenotype class per compound (needed for the scaffold-split "
          "stratification): not in the IDR files; to be taken from the paper's supplementary "
          "table in D2.", "",
          "## Points for the author", "",
          "1. idr0119's reporter is HDHB (not FUCCI); channel mapping (ii) uses R = NLS-mCherry, "
          "G = clover-HDHB, B = phase.",
          "2. idr0064 has one well per compound; the H2b unit (the compound) therefore has one "
          "well, and \"errors averaged over replicate wells\" averages over one well.",
          "3. AU565 single-drug wells were re-dosed at 48 h.", ""]
    res["idr0119"]["incomplete_fields"] = {
        f"{p}/{w}/{f}/{c}": int(n) for (p, w, f, c), n in slots[slots < 193].items()}
    res["idr0119"]["plates"] = int(ann.plate.nunique())
    res["idr0119"]["wells"] = int(len(ann))
    res["idr0119"]["fields"] = int(fields.sum())
    res["idr0119"]["files"] = int(len(fm))
    RES.parent.mkdir(parents=True, exist_ok=True)
    RES.write_text(json.dumps(res, indent=1, default=str))
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT.relative_to(REPO)} and {RES.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
